from __future__ import annotations
import json
from datetime import datetime
from pathlib import Path
from config import SAVED_MODELS_DIR, OUTPUTS_PLOTS_DIR, OUTPUTS_REPORTS_DIR
from evaluation.comparison import ModelComparison, PRIMARY_METRIC


def _read_svg(path: Path) -> str:
    if path.exists():
        return path.read_text()
    return "<p><em>Plot not found -- run train.py first.</em></p>"


def _results_table_html(results: dict, ranking_metric: str = PRIMARY_METRIC) -> str:
    ranking = ModelComparison.rank_models(results, metric=ranking_metric)
    rows = []
    for rank, (name, _) in enumerate(ranking, start=1):
        metrics = results[name]
        row_class = " class='best-row'" if rank == 1 else ""
        rows.append(
            f"<tr{row_class}><td>{rank}</td><td>{name}</td><td>{metrics['MAE']:.2f}</td><td>{metrics['RMSE']:.2f}</td><td>{metrics['MAPE']:.2f}%</td></tr>"
        )
    return (
        "<table><thead><tr><th>Rank</th><th>Model</th><th>MAE</th><th>RMSE</th><th>MAPE</th></tr></thead><tbody>"
        + "".join(rows)
        + "</tbody></table>"
    )


def generate_html_report(save_path: str | Path | None = None) -> Path:
    total_results = ModelComparison.load_results()
    per_country_path = Path(SAVED_MODELS_DIR) / "results_per_country.json"
    per_country_results = None
    if per_country_path.exists():
        with open(per_country_path) as f:
            per_country_results = json.load(f)
    comparison = ModelComparison.compare(total_results)
    best_model = comparison["best_model"]
    best_mape = total_results[best_model]["MAPE"]
    loss_svg = _read_svg(Path(OUTPUTS_PLOTS_DIR) / "mlp_total_training_loss.svg")
    comparison_svg = _read_svg(Path(OUTPUTS_PLOTS_DIR) / "model_comparison.svg")
    generated_at = datetime.now().strftime("%Y-%m-%d %H:%M")
    per_country_section = ""
    if per_country_results:
        per_country_section = f'\n    <h2>Per-country reference</h2>\n    <p class="muted">\n      For context: metrics from training one model per country and\n      averaging their accuracy (19 countries). The Total-series models\n      above -- trained directly on the nationwide aggregate -- are what\n      /predict actually serves, and are consistently far more accurate.\n    </p>\n    {_results_table_html(per_country_results)}\n'
    html = f'<!DOCTYPE html>\n<html lang="en">\n<head>\n<meta charset="UTF-8">\n<title>Tourism Forecast - Model Comparison Report</title>\n<style>\n  body {{ font-family: -apple-system, Helvetica, Arial, sans-serif; max-width: 900px; margin: 40px auto; padding: 0 20px; color: #1a1a1a; }}\n  h1 {{ font-size: 26px; margin-bottom: 4px; }}\n  h2 {{ font-size: 18px; margin-top: 40px; border-bottom: 1px solid #eee; padding-bottom: 8px; }}\n  .muted {{ color: #666; font-size: 14px; }}\n  .summary {{ background: #f0f9ff; border: 1px solid #bae6fd; border-radius: 8px; padding: 16px 20px; margin: 20px 0; }}\n  table {{ border-collapse: collapse; width: 100%; margin: 16px 0; }}\n  th, td {{ text-align: left; padding: 8px 12px; border-bottom: 1px solid #eee; font-size: 14px; }}\n  th {{ background: #fafafa; }}\n  .best-row {{ background: #f0fdf4; font-weight: 600; }}\n  .plot {{ margin: 20px 0; }}\n  svg {{ max-width: 100%; height: auto; }}\n  footer {{ margin-top: 50px; color: #999; font-size: 12px; }}\n</style>\n</head>\n<body>\n  <h1>Tourism Forecast - Model Comparison Report</h1>\n  <p class="muted">Generated {generated_at}</p>\n\n  <div class="summary">\n    <strong>{best_model}</strong> is the best-performing model, with a MAPE\n    of <strong>{best_mape:.2f}%</strong> on the held-out test period of the\n    nationwide aggregate arrivals series.\n  </div>\n\n  <h2>Model comparison (nationwide total &mdash; primary)</h2>\n  {_results_table_html(total_results)}\n\n  <div class="plot">{comparison_svg}</div>\n\n  <h2>MLP training loss</h2>\n  <div class="plot">{loss_svg}</div>\n  {per_country_section}\n  <footer>Generated by evaluation/report.py</footer>\n</body>\n</html>\n'
    save_path = (
        Path(save_path)
        if save_path
        else Path(OUTPUTS_REPORTS_DIR) / "model_comparison_report.html"
    )
    save_path.parent.mkdir(parents=True, exist_ok=True)
    save_path.write_text(html)
    return save_path


if __name__ == "__main__":
    path = generate_html_report()
    print(f"Report saved to: {path}")
